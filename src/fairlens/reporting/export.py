"""Exports: JSON, CSV, standalone HTML and PDF reports built from real run summaries or live analyses."""
from __future__ import annotations

import html
import io
import json
from datetime import datetime
from typing import Any

import pandas as pd

Section = tuple[str, list[Any]]  # (heading, blocks) where block = str paragraph | list[dict] table


def to_json(obj: Any) -> bytes:
    return json.dumps(obj, indent=2, default=str).encode("utf-8")


def to_csv(rows: list[dict] | pd.DataFrame) -> bytes:
    df = rows if isinstance(rows, pd.DataFrame) else pd.DataFrame(rows)
    return df.to_csv(index=False).encode("utf-8")


def _fmt(v):
    if isinstance(v, float):
        return f"{v:.3f}"
    if isinstance(v, (dict, list)):
        return json.dumps(v, default=str)[:200]
    return "" if v is None else str(v)


def to_html(title: str, sections: list[Section], meta: dict | None = None) -> bytes:
    css = ("body{font-family:Inter,Segoe UI,system-ui,sans-serif;color:#1B1A2E;background:#F6F5FD;margin:0;padding:32px}"
           ".wrap{max-width:1000px;margin:auto;background:#fff;border:1px solid #E6E3F5;border-radius:16px;padding:32px}"
           "h1{margin:0 0 4px;font-size:28px}h2{color:#6D4AFF;font-size:18px;margin-top:28px}.meta{color:#6B6A80;font-size:13px}"
           "table{border-collapse:collapse;width:100%;font-size:13px;margin:8px 0}th{background:#F0EEFC;text-align:left;padding:7px 9px}"
           "td{border-top:1px solid #E6E3F5;padding:7px 9px}p{line-height:1.55}.foot{margin-top:28px;color:#6B6A80;font-size:12px}")
    parts = [f"<h1>{html.escape(title)}</h1>"]
    if meta:
        parts.append('<div class="meta">' + " &middot; ".join(f"{html.escape(k)}: {html.escape(_fmt(v))}" for k, v in meta.items()) + "</div>")
    for head, blocks in sections:
        parts.append(f"<h2>{html.escape(head)}</h2>")
        for b in blocks:
            if isinstance(b, str):
                parts.append(f"<p>{html.escape(b)}</p>")
            elif b:
                cols = list(b[0])
                parts.append("<table><tr>" + "".join(f"<th>{html.escape(c)}</th>" for c in cols) + "</tr>" +
                             "".join("<tr>" + "".join(f"<td>{html.escape(_fmt(r.get(c)))}</td>" for c in cols) + "</tr>" for r in b) + "</table>")
    parts.append(f'<div class="foot">Generated by FairLens on {datetime.now():%Y-%m-%d %H:%M}. FairLens is a review assistant and '
                 "research framework; it cannot guarantee that any text is unbiased.</div>")
    return (f"<!doctype html><html><head><meta charset='utf-8'><title>{html.escape(title)}</title><style>{css}</style></head>"
            f"<body><div class='wrap'>{''.join(parts)}</div></body></html>").encode("utf-8")


def to_pdf(title: str, sections: list[Section], meta: dict | None = None) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=16 * mm, rightMargin=16 * mm, topMargin=16 * mm, bottomMargin=16 * mm,
                            title=title)
    ss = getSampleStyleSheet()
    ss["Heading2"].textColor = colors.HexColor("#6D4AFF")
    cell = ss["BodyText"].clone("cell", fontSize=7.5, leading=9)
    story = [Paragraph(html.escape(title), ss["Title"])]
    if meta:
        story.append(Paragraph(" &middot; ".join(f"<b>{html.escape(k)}</b>: {html.escape(_fmt(v))}" for k, v in meta.items()), ss["BodyText"]))
    for head, blocks in sections:
        story += [Spacer(1, 6), Paragraph(html.escape(head), ss["Heading2"])]
        for b in blocks:
            if isinstance(b, str):
                story.append(Paragraph(html.escape(b), ss["BodyText"]))
            elif b:
                cols = list(b[0])[:8]
                data = [[Paragraph(f"<b>{html.escape(c)}</b>", cell) for c in cols]] + \
                       [[Paragraph(html.escape(_fmt(r.get(c)))[:300], cell) for c in cols] for r in b[:60]]
                t = Table(data, repeatRows=1, colWidths=[(178 * mm) / len(cols)] * len(cols))
                t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F0EEFC")),
                                       ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#E6E3F5")),
                                       ("VALIGN", (0, 0), (-1, -1), "TOP")]))
                story.append(t)
    story += [Spacer(1, 10), Paragraph(f"Generated by FairLens on {datetime.now():%Y-%m-%d %H:%M}. FairLens is a review assistant and "
                                       "research framework; it cannot guarantee that any text is unbiased.", ss["Italic"])]
    doc.build(story)
    return buf.getvalue()


# --- section builders from stored summaries ---------------------------------------------------
def sections_for_run(kind: str, summary: dict) -> list[Section]:
    if kind == "benchmark_detection":
        rows = [{"detector": v.get("display", k), "precision": v["metrics"]["precision"], "recall": v["metrics"]["recall"],
                 "f1": v["metrics"]["f1"], "macro_f1": v["metrics"]["macro_f1"], "roc_auc": v["metrics"].get("roc_auc"),
                 "ece": v["metrics"]["ece"], "ms_per_sample": v.get("ms_per_sample"), "model_mb": v.get("model_mb")}
                for k, v in summary["detectors"].items() if v.get("status") == "ok"]
        return [("Detection on the shared test split", [f"n = {summary['n_test']} sentences; threshold 0.5.", rows])]
    if kind == "benchmark_mitigation":
        rw = [{"rewriter": k, **{m: v.get(m) for m in ["mean_bias_reduction_biased", "semantic_similarity", "fact_retention",
                                                         "fluency", "length_change", "unnecessary_change_rate_neutral"]}}
              for k, v in summary["rewriters"].items()]
        pol = [{"policy": k, **{m: v.get(m) for m in ["defer_rate", "accepted_fact_failure_rate", "unnecessary_change_rate",
                                                       "mean_bias_reduction_biased", "mean_semantic_similarity"]}}
               for k, v in summary["policies"].items()]
        return [("Rewriters", [rw]), ("Selection policies", [pol]),
                ("Gate decisions", [[{"decision": k, "inputs": v} for k, v in summary["gate_final_distribution"].items()]])]
    if kind == "benchmark_gate":
        cl = [{"variant": k, **{m: v.get(m) for m in ["macro_f1_3class", "accept_precision", "accept_recall", "unsafe_accept_rate",
                                                       "human_review_rate"]}} for k, v in summary["candidate_level"].items()]
        sel = [{"policy": k, "success": v["success"]["mean"], "harmful": v["harmful_selection"]["mean"], "defer": v["defer"]["mean"]}
               for k, v in summary["selection"].items()]
        abl = [{"ablation": k, "unsafe_accept_rate": v["metrics"]["unsafe_accept_rate"] if "metrics" in v else v.get("unsafe_accept_rate"),
                "delta": v.get("delta_unsafe_accept", {}).get("diff")} for k, v in summary["ablations"].items()]
        return [("Candidate-level decisions (test split)", [cl]), ("Input-level selection vs baselines", [sel]), ("Ablations", [abl])]
    if kind == "benchmark_image":
        rows = [{"captioner": v["display"], "clip": v["clip_similarity"]["mean"], "words": v["mean_words"],
                 "detail_coverage": v["detail_coverage"]["mean"], "flagged_rate": v["flagged_rate"],
                 "gender_term_rate": v["gender_term_rate_person_images"], "ms_per_image": v["ms_per_image"]}
                for v in summary["captioners"].values()]
        return [("Captioners", [summary.get("scope_note", ""), rows])]
    return [("Summary", [json.dumps(summary, default=str)[:4000]])]


def sections_for_analysis(analysis: dict | None, mitigation: dict | None) -> list[Section]:
    out: list[Section] = []
    if analysis:
        out.append(("Input", [analysis["text"]]))
        out.append(("Detector results", [[{"detector": v["display"], "score": v["score"], "label": v["label"],
                                           "runtime_ms": v["runtime_ms"]} for v in analysis["detector_results"].values()]]))
        if analysis["categories"]:
            out.append(("Detected categories", [[{"category": c["category"], "phrases": ", ".join(c["phrases"]),
                                                  "explanation": c["explanation"]} for c in analysis["categories"]]]))
    if mitigation:
        d = mitigation["decision"]
        out.append(("Reliability Gate", [f"Decision: {d['decision']} ({d['reason_code']}). {d['reason']}",
                                         f"Chosen: {d.get('chosen')} -> {d.get('chosen_text')}"]))
        out.append(("Candidates", [[{"candidate": c["candidate"], "text": c["text"], "verdict": c["verdict"],
                                     "bias_after": c["bias_after"], "similarity": c["semantic_similarity"],
                                     "fact_retention": c["fact_retention"]} for c in mitigation["candidates"]]]))
    return out


REVIEW_DISCLAIMER = "Review assistant, not a legal or compliance certification tool. FairLens cannot guarantee that any text is unbiased."


def sections_for_review(analysis: dict, mitigation: dict | None, evidence: list[dict], checks: list[tuple[str, bool | None, str]],
                        selected: str | None, reasons: dict[str, str]) -> list[Section]:
    """Report sections for the 6-step FairLens Review (job description) workflow."""
    out: list[Section] = [("Scope", [REVIEW_DISCLAIMER]), ("1. Input", [analysis["text"]])]
    flags = [{"phrase": e["phrase"], "category": e["category_label"], "flagged_by": ", ".join(e["flagged_by"]) or "rule match only",
              "rule_weight": e.get("weight"), "explanation": e["explanation"]} for e in evidence]
    det = [{"detector": v["display"], "score": v["score"], "label": v["label"]} for v in analysis["detector_results"].values()]
    out.append(("2. Flagged phrases and evidence", [f"Overall bias score {analysis['ensemble_score']:.2f} ({analysis['level']}).",
                                                    det, flags or "No phrases were flagged by the rule lexicon."]))
    if mitigation:
        cands = {c["candidate"]: c for c in mitigation["candidates"]}
        out.append(("3. Original vs proposed rewrites", [[{"version": k, "text": c["text"], "verdict": c["verdict"],
                                                           "bias_after": c["bias_after"]} for k, c in cands.items()]]))
        out.append(("4. Critical-fact preservation" + (f" ({selected})" if selected else ""),
                    [[{"check": n, "result": "n/a" if ok is None else "pass" if ok else "fail", "detail": d} for n, ok, d in checks]]))
        d = mitigation["decision"]
        out.append(("5. Reliability Gate verdict", [f"Decision: {d['decision']} ({d['reason_code']}). {d['reason']}",
                                                    f"Chosen version: {d.get('chosen') or 'none'}" + (f" -> {d['chosen_text']}" if d.get("chosen_text") else ""),
                                                    [{"version": c["candidate"], "verdict": c["verdict"], "reason_codes": ", ".join(c["reasons"]),
                                                      "meaning": " ".join(reasons.get(r, r) for r in c["reasons"])} for c in mitigation["candidates"]]]))
    return out
